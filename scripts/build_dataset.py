def build_files():
    # Save JSON
    json_path = os.path.join("data", "apps_dataset.json")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(APPS_DATA, f, indent=2, ensure_ascii=False)
    print(f"Saved {len(APPS_DATA)} apps to {json_path}")

    # Save CSV
    csv_path = os.path.join("data", "apps_dataset.csv")
    fieldnames = [
        "id", "name", "category", "description", "auth_methods", 
        "self_serve_vs_gated", "self_serve_status", "api_surface", 
        "mcp_status", "buildability_verdict", "main_blocker", 
        "evidence_url", "composio_fit"
    ]
    with open(csv_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in APPS_DATA:
            row_copy = row.copy()
            row_copy["auth_methods"] = ", ".join(row["auth_methods"])
            writer.writerow(row_copy)
    print(f"Saved {len(APPS_DATA)} apps to {csv_path}")

if __name__ == "__main__":
    build_files()
